List<ExchangeSession> createSeedSessions({DateTime? today}) {
  final now = today ?? DateTime.now();

  DateTime scheduled(int dayOffset, int hour, [int minute = 0]) {
    return DateTime(
      now.year,
      now.month,
      now.day + dayOffset,
      hour,
      minute,
    );
  }

