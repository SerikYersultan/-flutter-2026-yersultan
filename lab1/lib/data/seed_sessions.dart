    required String id,
    required String title,
    required ExchangeLanguage language,
    required int dayOffset,
    required int hour,
    int minute = 0,
    int limit = 10,
    List<String> participants = const [],
    bool online = false,
    required String place,
    String? description,
    bool favourite = false,
  }) {
